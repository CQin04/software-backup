"""Verify all five MCP tools using temporary, public test fixtures only."""
from __future__ import annotations
import asyncio
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import sys
import tempfile

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

ROOT = Path(__file__).resolve().parent
TOOLS = {'everything_search', 'everything_search_by_type', 'everything_find_recent',
         'everything_file_details', 'everything_count_stats'}


def response_text(response):
    text = '\n'.join(c.text for c in response.content if c.type == 'text')
    if getattr(response, 'is_error', getattr(response, 'isError', False)) or text.startswith('Error:'):
        raise AssertionError(text)
    if '\ufffd' in text:
        raise AssertionError('A returned path contains a Unicode replacement character')
    return text


async def main():
    runtime = ROOT / 'runtime'
    runtime.mkdir(exist_ok=True)
    assert runtime.resolve().is_relative_to(ROOT.resolve())
    report = {'checked_at_utc': datetime.now(timezone.utc).isoformat(), 'passed': False, 'checks': []}
    # The temporary tree is created inside this explicitly named package directory.
    # Cleanup removes only files generated by this verification run.
    try:
        with tempfile.TemporaryDirectory(prefix='中文路径验证-', dir=runtime) as directory:
            fixture = Path(directory).resolve()
            assert fixture.is_relative_to(runtime.resolve())
            document = fixture / '验证说明.md'
            archive = fixture / '验证归档.zip'
            document.write_text('# Public MCP test fixture\n', encoding='utf-8')
            archive.write_bytes(b'Public archive-type search fixture; not an installable package.')
            params = StdioServerParameters(
                command=sys.executable, args=['-B', '-m', 'everything_mcp'],
                env={**os.environ, 'EVERYTHING_ES_PATH': str(ROOT / 'bin' / 'es.exe'),
                     'EVERYTHING_MAX_RESULTS_CAP': '200', 'PYTHONUTF8': '0', 'PYTHONIOENCODING': 'utf-8'},
            )
            async with stdio_client(params) as (reader, writer):
                async with ClientSession(reader, writer) as session:
                    await session.initialize()
                    tools = (await session.list_tools()).tools
                    assert {t.name for t in tools} == TOOLS
                    assert all(t.annotations and getattr(t.annotations, 'read_only_hint', getattr(t.annotations, 'readOnlyHint', False)) for t in tools)
                    report['checks'].append('five_read_only_tools_discovered')
                    query = f'path:"{fixture}" ext:md'
                    # Wait briefly for Everything to observe these newly created fixtures.
                    for attempt in range(20):
                        result = response_text(await session.call_tool('everything_search', {'params': {
                            'query': query, 'max_results': 5, 'sort': 'name'}}))
                        if str(document) in result:
                            break
                        await asyncio.sleep(0.25)
                    assert str(document) in result, 'New fixture was not indexed'
                    report['checks'].append('exact_chinese_path_search')
                    result = response_text(await session.call_tool('everything_search_by_type', {'params': {
                        'file_type': 'archive', 'path': str(fixture), 'max_results': 5, 'sort': 'name'}}))
                    assert str(archive) in result
                    report['checks'].append('archive_type_search')
                    result = response_text(await session.call_tool('everything_find_recent', {'params': {
                        'period': 'today', 'path': str(fixture), 'extensions': 'md', 'max_results': 5}}))
                    assert str(document) in result
                    report['checks'].append('recent_documents')
                    result = response_text(await session.call_tool('everything_file_details', {'params': {
                        'paths': [str(document)], 'preview_lines': 0}}))
                    details = json.loads(result)
                    assert details['path'] == str(document) and details['size'] == document.stat().st_size
                    report['checks'].append('metadata_without_content_preview')
                    result = response_text(await session.call_tool('everything_count_stats', {'params': {
                        'query': query, 'include_size': True, 'breakdown_by_extension': False}}))
                    assert json.loads(result)['total_count'] == 1
                    report['checks'].append('count_and_size')
            report['passed'] = True
    except BaseException as error:
        report['error_type'] = type(error).__name__
        raise
    finally:
        (runtime / 'verification.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
        print(json.dumps(report, ensure_ascii=False))


if __name__ == '__main__':
    asyncio.run(main())

